export const dictionaries = { en, ru };
export type Lang = keyof typeof dictionaries;

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("lodestone.lang");
    if (saved === "en" || saved === "ru") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function translator(lang: Lang) {
  const d = dictionaries[lang];
  return (key: TKey, vars?: Record<string, string | number>) => {
    let s: string = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export type T = ReturnType<typeof translator>;
export const I18n = createContext<{ t: T; lang: Lang; setLang: (l: Lang) => void }>({
  t: translator("en"),
  lang: "en",
  setLang: () => {},
});
export const useT = () => useContext(I18n);
